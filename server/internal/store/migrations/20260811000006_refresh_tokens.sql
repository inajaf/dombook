-- 0006_refresh_tokens.sql — rotating refresh credentials.
--
-- A refresh token is a long-lived credential, which makes it the most valuable
-- thing a stolen device holds. Rotation is the standard mitigation: each use
-- consumes the token and issues a successor, so a stolen token is usable at most
-- once before the legitimate client's next refresh invalidates the chain.
--
-- Reuse detection is the part that turns rotation into an actual defence. If a
-- token that has already been consumed is presented again, one of two things is
-- true: the attacker is replaying a stolen token, or the legitimate client is
-- retrying. Both cases are treated as compromise, because the cost of a false
-- positive (one forced re-login) is far below the cost of a miss.
--
-- These are pre-tenant operations: the caller presents a token, not a session, so
-- no app.tenant_id exists. Hence SECURITY DEFINER, with search_path pinned and
-- PUBLIC revoked, following the rules in 0004/0005.

-- ---------------------------------------------------------------------------
-- Storage
-- ---------------------------------------------------------------------------

-- Issues a refresh token.
--
-- The plaintext token is generated by the application and stored only as a hash:
-- a database leak must not yield usable credentials. family_id groups every token
-- descended from one login, so a reuse anywhere in the chain can revoke the whole
-- family at once instead of trying to walk it link by link.
CREATE OR REPLACE FUNCTION issue_refresh_token(
  p_id         uuid,
  p_family_id  uuid,
  p_account_id uuid,
  p_user_id    uuid,
  p_device_id  uuid,
  p_token_hash text,
  p_expires_at timestamptz
) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
  INSERT INTO refresh_tokens (id, family_id, account_id, user_id, device_id, token_hash, expires_at)
  VALUES (p_id, p_family_id, p_account_id, p_user_id, p_device_id, p_token_hash, p_expires_at);
END
$$;

-- Consumes a refresh token and returns what it stood for.
--
-- The UPDATE is conditional on the token being live, which is what makes
-- consumption atomic: two concurrent refreshes cannot both succeed, so a replayed
-- token always loses the race and is reported as reuse rather than silently
-- minting a second session.
--
-- Returns no rows when the token is unknown, expired, or already consumed. The
-- caller distinguishes "already consumed" from "unknown" with
-- refresh_token_family(), because the responses differ: reuse must revoke the
-- family, an unknown token is simply rejected.
CREATE OR REPLACE FUNCTION consume_refresh_token(
  p_token_hash text
) RETURNS TABLE (
  token_id    uuid,
  family_id   uuid,
  account_id  uuid,
  user_id     uuid,
  device_id   uuid,
  was_used    boolean
)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
  -- Report the pre-consumption state so the caller can tell reuse from a first use.
  RETURN QUERY
  SELECT t.id, t.family_id, t.account_id, t.user_id, t.device_id, (t.used_at IS NOT NULL)
    FROM refresh_tokens t
   WHERE t.token_hash = p_token_hash
     AND t.revoked_at IS NULL
     AND t.expires_at > now()
   LIMIT 1;

  UPDATE refresh_tokens
     SET used_at = now()
   WHERE token_hash = p_token_hash
     AND used_at IS NULL
     AND revoked_at IS NULL
     AND expires_at > now();
END
$$;

-- Reports the family a token belongs to, even once consumed or revoked. Used to
-- decide whether a rejected token indicates compromise.
CREATE OR REPLACE FUNCTION refresh_token_family(
  p_token_hash text
) RETURNS TABLE (
  token_id   uuid,
  family_id  uuid,
  account_id uuid,
  user_id    uuid,
  revoked    boolean,
  used       boolean,
  expired    boolean
)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
  SELECT t.id, t.family_id, t.account_id, t.user_id,
         (t.revoked_at IS NOT NULL),
         (t.used_at IS NOT NULL),
         (t.expires_at <= now())
    FROM refresh_tokens t
   WHERE t.token_hash = p_token_hash
   LIMIT 1
$$;

-- Revokes every token in a family. Called on reuse detection and on "sign out
-- everywhere". Returns how many were revoked, so the caller can log the blast
-- radius rather than assuming it.
CREATE OR REPLACE FUNCTION revoke_refresh_family(p_family_id uuid) RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  affected integer;
BEGIN
  UPDATE refresh_tokens
     SET revoked_at = now()
   WHERE family_id = p_family_id AND revoked_at IS NULL;
  GET DIAGNOSTICS affected = ROW_COUNT;
  RETURN affected;
END
$$;

-- Revokes every refresh token for a user, across all families and devices.
CREATE OR REPLACE FUNCTION revoke_user_refresh_tokens(p_user_id uuid) RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  affected integer;
BEGIN
  UPDATE refresh_tokens
     SET revoked_at = now()
   WHERE user_id = p_user_id AND revoked_at IS NULL;
  GET DIAGNOSTICS affected = ROW_COUNT;
  RETURN affected;
END
$$;

-- Resolves a user id to the identity a refreshed session needs.
--
-- A refresh happens without a session, so the users table cannot be read through
-- its tenant policy. Returns only what minting a new access token requires.
CREATE OR REPLACE FUNCTION lookup_user_for_refresh(
  p_user_id uuid
) RETURNS TABLE (
  id           uuid,
  account_id   uuid,
  email        citext,
  name         text,
  role         text,
  account_name text,
  plan         text
)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
  SELECT u.id, u.account_id, u.email, u.name, u.role, a.name, a.plan
    FROM users u
    JOIN accounts a ON a.id = u.account_id
   WHERE u.id = p_user_id
   LIMIT 1
$$;

