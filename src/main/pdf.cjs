/**
 * HTML to PDF, through the browser engine Electron already ships.
 *
 * The alternative — a PDF library — would mean hand-laying-out every line of a contract and a
 * second text-shaping stack in the bundle, to produce a worse-looking page than the renderer that
 * is already here. `printToPDF` is the same path the OS print dialog takes, so what the owner
 * prints and what the file contains cannot drift apart.
 *
 * The document is written to a temporary file and loaded with `loadFile` rather than passed as a
 * `data:` URL: a contract with a long note in it exceeds what is comfortable to encode into a
 * URL, and a truncated document would render as a blank page with no error.
 */

const fs = require("node:fs/promises");
const os = require("node:os");
const path = require("node:path");
const { BrowserWindow } = require("electron");

/**
 * Render `html` to a PDF at `filePath`.
 *
 * The window is offscreen and has JavaScript disabled: the document is generated by this process
 * from stored rows, and a script that ran inside it could only be a way for a guest's name to
 * reach something it should not.
 */
async function renderHtmlToPdf(html, filePath) {
  const temporary = path.join(os.tmpdir(), `rentkeeper-doc-${process.pid}-${Date.now()}.html`);
  await fs.writeFile(temporary, html, "utf8");

  const window = new BrowserWindow({
    show: false,
    webPreferences: { sandbox: true, javascript: false, contextIsolation: true },
  });
  try {
    await window.loadFile(temporary);
    // A page is printed once, and a document that is still settling produces a SHORT one.
    //
    // A two-page contract came out as a single page on one occasion: the clauses and the signature
    // block were simply absent, and the file was a valid PDF that opened normally and ended
    // mid-sentence. It has NOT been reproduced since — 20 generations, with and without
    // `preferCSSPageSize`, all produced two pages — so this wait is a mitigation for an
    // unexplained truncation, not a fix for a diagnosed one.
    //
    // The guard that matters is in scripts/e2e-documents.mjs, which asserts a page count. A
    // truncated PDF passes every other check there is, including "the file is a PDF" and "it is
    // not empty": it is a perfectly valid one-page document that happens to be missing its end.
    await new Promise((resolve) => setTimeout(resolve, 200));
    const pdf = await window.webContents.printToPDF({
      printBackground: true,
      pageSize: "A4",
      // `preferCSSPageSize` is left unset: the document's own `@page { margin }` is honoured
      // either way, and no evidence says turning it on changes the output.
    });
    await fs.mkdir(path.dirname(filePath), { recursive: true });
    await fs.writeFile(filePath, pdf);
    return filePath;
  } finally {
    window.destroy();
    await fs.rm(temporary, { force: true });
  }
}

module.exports = { renderHtmlToPdf };
